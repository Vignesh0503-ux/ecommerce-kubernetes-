package com.ecommerce.orderservice.client;

/**
 * Minimal representation of a User as returned by the User Service.
 * Kept separate from the User Service's own entity on purpose -
 * each microservice owns its own model (no shared library).
 */
public class UserDto {

    private Long id;
    private String name;
    private String email;
    private String phone;

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getPhone() {
        return phone;
    }

    public void setPhone(String phone) {
        this.phone = phone;
    }
}
